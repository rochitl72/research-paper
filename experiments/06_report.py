"""Build docs/results_tables.md from results/<model>/*.json (no hand-copied numbers).

    python experiments/06_report.py --models Qwen/Qwen3-0.6B-Base Qwen/Qwen3-1.7B-Base
"""
import argparse
import json

from common import RESULTS, ROOT, slug

LANG = {"ta": "Tamil", "hi": "Hindi", "en": "English"}


def load(model, name):
    p = RESULTS / slug(model) / f"{name}.json"
    return json.loads(p.read_text()) if p.exists() else None


def pct(x):
    return f"{100 * x:.1f}%"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--models", nargs="+", default=["Qwen/Qwen3-0.6B-Base"])
    args = ap.parse_args()
    L = ["# Result tables", "", "Generated by `experiments/06_report.py` from `results/`. Do not edit by hand.", ""]
    for m in args.models:
        name = slug(m)
        meta, sp, pr, pa, hd = (load(m, n) for n in ("corpus_pass_meta", "spelling_share", "plan_probe", "patching", "heads_and_decoding"))
        L += [f"## {name}", ""]
        if meta:
            e = meta["env"]
            L += [f"Run on {e['platform']} ({e['device']}, {e['dtype'].replace('torch.', '')}), torch {e['torch']}, "
                  f"transformers {e['transformers']}. {e['n_layers']} layers, d = {e['d_model']}.", ""]
            L += ["| Language | Split | Paragraphs | Tokens | Seconds | Tokens/s |", "| --- | --- | ---: | ---: | ---: | ---: |"]
            for r in meta["runs"]:
                L.append(f"| {LANG[r['lang']]} | {r['split']} | {r['paragraphs']} | {r['tokens']:,} | {r['seconds']:.0f} | {r['tokens'] / r['seconds']:.0f} |")
            L.append("")
        if sp:
            L += ["### Spelling share", "",
                  "| Language | Words | Tokens/word | Multi-token words | Continuation tokens | p ≥ 0.5 | p ≥ 0.9 | p ≥ 0.99 | Greedy-correct continuations | Word bits in first token |",
                  "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |"]
            for l, s in sp.items():
                L.append(f"| {LANG[l]} | {s['n_words']:,} | {s['tokens_per_word']:.2f} | {pct(s['share_words_multitoken'])} | "
                         f"{pct(s['cont_share_of_word_tokens'])} | {pct(s['spelling_share@0.5'])} | {pct(s['spelling_share@0.9'])} | "
                         f"{pct(s['spelling_share@0.99'])} | {pct(s['cont_greedy_correct'])} | {pct(s['share_bits_in_first_token'])} |")
            L += ["", "The p columns are shares of all word tokens that are continuation tokens with model probability at least p.", "",
                  "| Language | Boundary type | Share of continuation tokens | Near-certain (p ≥ 0.9) |", "| --- | --- | ---: | ---: |"]
            for l, s in sp.items():
                for b in ("byte", "grapheme", "subword"):
                    if b in s["boundary_share_of_cont"]:
                        L.append(f"| {LANG[l]} | {b} | {pct(s['boundary_share_of_cont'][b])} | {pct(s['boundary_deterministic@0.9'][b])} |")
            L.append("")
        if pr:
            L += ["### Plan probe at the position before the word", ""]
            for l, d in pr.items():
                r = d.get("by_layer") or []
                if not r:
                    continue
                L += [f"{LANG[l]}: {r[0]['n_classes']} candidate words, {r[0]['n_test']:,} held-out occurrences, 3 seeds.", "",
                      "| Layer | Probe | Most frequent word | Shuffled-label control | Uniform chance | Probe, model spells word | Probe, model misspells |",
                      "| ---: | ---: | ---: | ---: | ---: | ---: | ---: |"]
                for a in r:
                    L.append(f"| {a['layer']} | {pct(a['acc'])} ± {100 * a['acc_sd']:.1f} | {pct(a['acc_majority'])} | {pct(a['acc_control'])} | "
                             f"{pct(a['acc_chance'])} | {pct(a['acc_model_spells'])} | {pct(a['acc_model_misspells'])} |")
                L.append("")
                if d.get("by_position"):
                    L += ["| Tokens written | Probe on state | Prefix-only dictionary | Gap | Candidate words | n |", "| ---: | ---: | ---: | ---: | ---: | ---: |"]
                    for a in d["by_position"]:
                        L.append(f"| {a['prefix_tokens']} | {pct(a['acc_state'])} | {pct(a['acc_prefix_only'])} | "
                                 f"{100 * (a['acc_state'] - a['acc_prefix_only']):+.1f} | {a['mean_candidates']:.0f} | {a['n_test']:,} |")
                    L.append("")
        if pa:
            L += ["### Activation patching", ""]
            for l in ("ta", "hi", "en"):
                if l not in pa:
                    continue
                pre, ft = pa[l]["preword"], pa[l]["first_token"]
                L += [f"{LANG[l]}: {pre['n_pairs']} context pairs. Effect = shift of the next-token logit difference toward the donor word (median, with quartiles).", "",
                      "| Layer | Pre-word position | (q25, q75) | First-token position (control) | Donor word spelled after pre-word patch | after first-token patch |",
                      "| ---: | ---: | --- | ---: | ---: | ---: |"]
                for i, Lr in enumerate(pre["layers"]):
                    L.append(f"| {Lr} | {pre['effect_median'][i]:+.2f} | ({pre['effect_q25'][i]:+.2f}, {pre['effect_q75'][i]:+.2f}) | "
                             f"{ft['effect_median'][i]:+.2f} | {pct(pre['transfer_rate'][i])} | {pct(ft['transfer_rate'][i])} |")
                L.append("")
        ko = load(m, "knockout")
        if ko:
            L += ["### Attention knockout", "",
                  "Attention from the word's own positions to one context position is blocked at every layer. "
                  "Change in log-probability of the word's continuation tokens, on words the model spells correctly.", "",
                  "| Language | Words | Blocked position | Mean change (bits) | Median (bits) | Still spelled correctly |", "| --- | ---: | --- | ---: | ---: | ---: |"]
            for l in ("ta", "hi", "en"):
                if l not in ko:
                    continue
                for k, lab in (("preword", "last token before the word"), ("preword_minus_1", "token before that"), ("random_context", "random earlier token")):
                    r = ko[l][k]
                    L.append(f"| {LANG[l]} | {ko[l]['n_words']} | {lab} | {r['mean_delta_bits']:+.2f} | {r['median_delta_bits']:+.2f} | {pct(r['still_spelled'])} |")
            L.append("")
        if hd:
            L += ["### Drafters: decoder emulation on held-out text", ""]
            for l in ("ta", "hi", "en"):
                if l not in hd:
                    continue
                d = hd[l]
                L += [f"{LANG[l]}: head lexicon {d['head_lexicon']:,} words (covers {pct(d['coverage_head_lexicon'])} of held-out multi-token word "
                      f"occurrences); dictionary {d['dictionary_lexicon']:,} words (covers {pct(d['coverage_dictionary'])}).", "",
                      "| Drafter | Forward passes per word token | Word tokens per pass | Draft acceptance | Whole word on first draft |",
                      "| --- | ---: | ---: | ---: | ---: |"]
                for k, e in d["emulation"].items():
                    L.append(f"| {k} | {e['steps_per_token']:.3f} | ×{e['step_reduction']:.2f} | {pct(e['acceptance'])} | {pct(e['whole_word_first_draft'])} |")
                L.append("")
                dec = d["decoding"]
                L += [f"Real greedy decoding from held-out prompts ({len(next(iter(dec['per_prompt'].values())))} prompts). "
                      f"Output identical to plain greedy on every prompt: **{dec['lossless']}**.", "",
                      "| Drafter | Tokens per forward pass | Draft acceptance | Wall-clock speedup |", "| --- | ---: | ---: | ---: |"]
                for k, e in dec["summary"].items():
                    L.append(f"| {k} | {e['tokens_per_forward']:.2f} | {pct(e['acceptance'])} | ×{e['wallclock_speedup']:.2f} |")
                L.append("")
    out = ROOT / "docs" / "results_tables.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(L) + "\n")
    print("wrote", out)


if __name__ == "__main__":
    main()
